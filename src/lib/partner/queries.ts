import { and, desc, eq, gte, lte, sql } from "drizzle-orm";
import type { Db } from "../db/client";
import { bots, feeEvents, feePolicyVersions, ledgerEntries, partners, payouts, users } from "../db/schema";
import { payableBalance } from "../ledger/service";
import { referralCounts } from "../referral/service";

export function maskAddress(addr: string) {
  return `${addr.slice(0, 6)}…${addr.slice(-4)}`;
}

export async function partnerSummary(db: Db, userId: string) {
  const [partner] = await db.select().from(partners).where(eq(partners.userId, userId)).limit(1);
  if (!partner) return null;
  const counts = await referralCounts(db, userId);
  const [tiers] = await db
    .select({
      tier1: sql<string>`coalesce(-sum(${ledgerEntries.amountE8}) filter (where ${ledgerEntries.tier} = 1), 0)`,
      tier2: sql<string>`coalesce(-sum(${ledgerEntries.amountE8}) filter (where ${ledgerEntries.tier} = 2), 0)`,
    })
    .from(ledgerEntries)
    .where(and(eq(ledgerEntries.account, "PARTNER_PAYABLE"), eq(ledgerEntries.accountUserId, userId), sql`${ledgerEntries.feeEventId} is not null`));
  const [paid] = await db
    .select({ total: sql<string>`coalesce(sum(${payouts.amountE8}), 0)` })
    .from(payouts)
    .where(and(eq(payouts.recipientUserId, userId), eq(payouts.account, "PARTNER_PAYABLE"), eq(payouts.status, "PAID")));
  // Builder fee generated by referred traders (both tiers), allocated or not.
  const [generated] = await db
    .select({
      observed: sql<string>`coalesce(sum(${feeEvents.amountE8}) filter (where ${feeEvents.status} = 'OBSERVED'), 0)`,
      confirmed: sql<string>`coalesce(sum(${feeEvents.amountE8}) filter (where ${feeEvents.status} = 'ALLOCATED'), 0)`,
    })
    .from(feeEvents)
    .where(sql`${feeEvents.tier1PartnerUserId} = ${userId} or ${feeEvents.tier2PartnerUserId} = ${userId}`);
  return {
    partner,
    counts,
    tier1EarnedE8: BigInt(tiers?.tier1 ?? "0"),
    tier2EarnedE8: BigInt(tiers?.tier2 ?? "0"),
    paidE8: BigInt(paid?.total ?? "0"),
    unpaidE8: await payableBalance(db, userId, "PARTNER_PAYABLE"),
    referredFeesObservedE8: BigInt(generated?.observed ?? "0"),
    referredFeesConfirmedE8: BigInt(generated?.confirmed ?? "0"),
  };
}

export interface EarningsFilter {
  from?: Date;
  to?: Date;
  tier?: 1 | 2;
  botId?: string;
}

/** Partner earnings lines. Trader identities are masked (privacy minimization). */
export async function partnerEarnings(db: Db, userId: string, f: EarningsFilter = {}, limit = 500) {
  const rows = await db
    .select({
      entryId: ledgerEntries.id,
      tier: ledgerEntries.tier,
      amountE8: ledgerEntries.amountE8,
      createdAt: ledgerEntries.createdAt,
      occurredAt: feeEvents.occurredAt,
      feeE8: feeEvents.amountE8,
      botName: bots.name,
      botId: feeEvents.botId,
      trader: users.walletAddress,
      policyVersion: feePolicyVersions.version,
    })
    .from(ledgerEntries)
    .innerJoin(feeEvents, eq(feeEvents.id, ledgerEntries.feeEventId))
    .innerJoin(users, eq(users.id, feeEvents.traderUserId))
    .innerJoin(feePolicyVersions, eq(feePolicyVersions.id, feeEvents.feePolicyVersionId))
    .leftJoin(bots, eq(bots.id, feeEvents.botId))
    .where(
      and(
        eq(ledgerEntries.account, "PARTNER_PAYABLE"),
        eq(ledgerEntries.accountUserId, userId),
        f.tier ? eq(ledgerEntries.tier, f.tier) : undefined,
        f.botId ? eq(feeEvents.botId, f.botId) : undefined,
        f.from ? gte(feeEvents.occurredAt, f.from) : undefined,
        f.to ? lte(feeEvents.occurredAt, f.to) : undefined,
      ),
    )
    .orderBy(desc(feeEvents.occurredAt))
    .limit(limit);
  return rows.map((r) => ({
    entryId: r.entryId,
    tier: r.tier,
    earnedE8: -r.amountE8,
    builderFeeE8: r.feeE8,
    occurredAt: r.occurredAt,
    bot: r.botName ?? "수동 주문",
    trader: maskAddress(r.trader),
    policyVersion: r.policyVersion,
  }));
}
